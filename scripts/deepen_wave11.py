def faq_json(faqs: list[tuple[str, str]]) -> str:
    entities = []
    for q, a in faqs:
        entities.append({
            "@type": "Question",
            "name": q,
            "acceptedAnswer": {"@type": "Answer", "text": a},
        })
    return json.dumps(
        {"@context": "https://schema.org", "@type": "FAQPage", "mainEntity": entities},
        ensure_ascii=False,
        separators=(",", ":"),
    )


def replace_container(html: str, new_body: str) -> str:
    return re.sub(
        r'(<article class="article-body">.*?<div class="container">)(.*?)(</div>\s*</article>)',
        lambda m: m.group(1) + new_body.strip() + "\n" + m.group(3),
        html,
        count=1,
        flags=re.S,
    )


def upsert_faq_schema(html: str, faqs: list[tuple[str, str]]) -> str:
    block = f'<script type="application/ld+json">{faq_json(faqs)}</script>'
    if re.search(r'"@type"\s*:\s*"FAQPage"', html):
        return re.sub(
            r'<script type="application/ld\+json">\{[^<]*"@type"\s*:\s*"FAQPage"[^<]*\}</script>',
            block,
            html,
            count=1,
        )
    return html.replace("</head>", block + "\n</head>", 1)


def fix_hero_alt(html: str, alt: str) -> str:
    html = re.sub(
        r'(<section class="article-banner"[^>]*>.*?<img[^>]*alt=")[^"]*(")',
        rf"\1{alt}\2",
        html,
        count=1,
        flags=re.S,
    )
    html = re.sub(
        r'(<figure class="hero"><img[^>]*alt=")[^"]*(")',
        rf"\1{alt}\2",
        html,
        count=1,
    )
    return html


def fix_meta_em_dash(html: str) -> str:
    return html.replace("—", "،")


def update_toc(html: str, items: list[tuple[str, str]]) -> str:
    links = "\n".join(f'<a href="{h}" class="toc-item">{t}</a>' for h, t in items)
    new_toc = f'<div class="sidebar-module sidebar-toc"><h4>📑 Contents</h4>\n{links}\n</div>'
    return re.sub(
        r'<div class="sidebar-module sidebar-toc">.*?</div>',
        new_toc,
        html,
        count=1,
        flags=re.S,
    )


def patch(path: str) -> None:
    fp = ROOT / path
    html = fp.read_text(encoding="utf-8")
    html = replace_container(html, BODY_MAP[path])
    html = upsert_faq_schema(html, FAQ_DATA[path])
    html = fix_hero_alt(html, HERO_ALT[path])
    html = fix_meta_em_dash(html)
    html = update_toc(html, TOC_MAP[path])
    if "barakah" in path:
        html = re.sub(
            r'<div class="article-tags">.*?</div>',
            '<div class="article-tags">\n  <span class="tag">#finance</span>\n  <span class="tag">#family-budget</span>\n  <span class="tag">#islamic-finance</span>\n  <span class="tag">#gulf-families</span>\n</div>',
            html,
            count=1,
            flags=re.S,
        )
        html = re.sub(
            r'<h3><span class="en">Try Our حاسبة BMI</span><span class="ar">جرّب حاسبة BMI</span></h3>',
            '<h3><span class="en">Try Our Zakat Calculator</span><span class="ar">جرّب حاسبة الزكاة</span></h3>',
            html,
        )
        html = re.sub(
            r'href="/tools/bmi-calculator\.html" class="tool-cta-btn"',
            'href="/tools/zakat-calculator.html" class="tool-cta-btn"',
            html,
            count=1,
        )
    fp.write_text(html, encoding="utf-8")
    print(f"Patched {path}")


def main() -> int:
    for path in BODY_MAP:
        patch(path)
    r = subprocess.run(
        ["python3", "scripts/amer_gate.py", *BODY_MAP.keys()],
        cwd=ROOT,
        capture_output=True,
        text=True,
    )
    print(r.stdout)
    if r.returncode != 0:
        print(r.stderr, file=sys.stderr)
        return 1
    fails = [ln for ln in r.stdout.splitlines() if ln.startswith("FAIL")]
    return 1 if fails else 0


if __name__ == "__main__":
    raise SystemExit(main())
