def fix_meta_em_dash(html: str) -> str:
    return html.replace("—", "،")


def update_toc(html: str, items: list[tuple[str, str]]) -> str:
    links = "\n".join(f'<a href="{h}" class="toc-item">{t}</a>' for h, t in items)
    new_toc = f'<div class="sidebar-module sidebar-toc"><h4>📑 Contents</h4>\n{links}\n</div>'
    return re.sub(
        r'<div class="sidebar-module sidebar-toc">.*?</div>',
        new_toc,
        html,
        count=1,
        flags=re.S,
    )


def patch(path: str) -> None:
    fp = ROOT / path
    html = fp.read_text(encoding="utf-8")
    html = replace_container(html, BODY_MAP[path])
    html = upsert_faq_schema(html, FAQ_DATA[path])
    html = fix_hero_alt(html, HERO_ALT[path])
    html = fix_meta_em_dash(html)
    html = update_toc(html, TOC_MAP[path])
    html = re.sub(r'"dateModified":"[^"]+"', '"dateModified":"2026-07-08"', html, count=1)
    if "listening-gift" in path:
        html = re.sub(
            r'<div class="article-tags">.*?</div>',
            '<div class="article-tags">\n  <span class="tag">#peace</span>\n  <span class="tag">#parenting</span>\n  <span class="tag">#family</span>\n  <span class="tag">#gulf-families</span>\n</div>',
            html,
            count=1,
            flags=re.S,
        )
    if "father-quit" in path:
        html = re.sub(
            r'<div class="article-tags">.*?</div>',
            '<div class="article-tags">\n  <span class="tag">#digital-minimalism</span>\n  <span class="tag">#fatherhood</span>\n  <span class="tag">#family</span>\n  <span class="tag">#gulf-families</span>\n</div>',
            html,
            count=1,
            flags=re.S,
        )
    fp.write_text(html, encoding="utf-8")
    print(f"Patched {path}")


def main() -> int:
    for path in BODY_MAP:
        patch(path)
    r = subprocess.run(
        ["python3", "scripts/amer_gate.py", *BODY_MAP.keys()],
        cwd=ROOT,
        capture_output=True,
        text=True,
    )
    print(r.stdout)
    fails = [ln for ln in r.stdout.splitlines() if ln.startswith("FAIL")]
    return 1 if fails else 0


if __name__ == "__main__":
    raise SystemExit(main())
